// ============================================================
// Topic: Variables
// Purpose: Used to store and manage data in a program.
// Keywords: var, let, const
// Changes Original Value? let and var can be reassigned; const cannot.
// Returns: Stores a value in a variable.
// Example 1 - let
let userName = "Ananya";
console.log(userName);
userName = "Meera";
console.log(userName);

// Example 2 - const
const company = "Tech Solutions";
console.log(company);

// Example 3 - Multiple Variables
let age = 27;
let role = "QA Engineer";
console.log(age);
console.log(role);
